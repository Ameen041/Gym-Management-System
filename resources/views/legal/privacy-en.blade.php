<p class="legal-lead">Himma collects only what it needs to give you the service, and never sells your data. This page explains what we collect, who sees it and how you control it.</p>

<h2 id="collect">1. What we collect</h2>
<ul>
  <li><strong>Your account:</strong> name, email, phone number and password (stored hashed, nobody can read it).</li>
  <li><strong>When you subscribe:</strong> age, height, weight, goal, health answers and notes, food allergies, and body photos if you add them.</li>
  <li><strong>During a subscription:</strong> weekly check-ins and their photos, chat messages, and your review of the coach.</li>
  <li><strong>Payment:</strong> the Sham Cash receipt and transaction number. We never ask for or keep your Sham Cash password.</li>
  <li><strong>Coaches:</strong> profile, certificates and the Sham Cash account for payouts.</li>
  <li><strong>Technical:</strong> your network address (IP) at login, to protect accounts, and the cookies needed to stay logged in and remember your language and dark mode. No ads, no trackers.</li>
</ul>

<h2 id="use">2. Why we use it</h2>
<ul>
  <li>So your coach can build your plan and follow you up safely.</li>
  <li>To confirm payments, pay coaches, solve problems and give support.</li>
  <li>To protect the platform from fraud and from payments outside it.</li>
  <li>To send notifications in Himma, and to your phone if you turn them on.</li>
</ul>

<h2 id="who">3. Who sees your data</h2>
<ul>
  <li><strong>Your coach:</strong> your answers, photos, check-ins and your chat. Not your phone number or payment receipt.</li>
  <li><strong>The Himma team:</strong> to manage subscriptions, payments and support. They read a chat only if one of you reports it or to settle a dispute, and they see messages that were stopped for holding contact details.</li>
  <li><strong>Visitors:</strong> coach profiles, photos and reviews are public. A review shows your first name only.</li>
  <li>We never sell your data or share it with advertisers, and disclose it only to an official authority that asks for it under the law.</li>
</ul>

<h2 id="keep">4. Where we keep it and for how long</h2>
<ul>
  <li>Data is kept on Himma's servers with a daily backup. Photos and receipts have no public link; only accounts allowed to see them can open them.</li>
  <li>We keep your data while your account exists. When an account is deleted we delete its data, except payment records needed for accounting.</li>
</ul>

<h2 id="rights">5. Your rights</h2>
<ul>
  <li>See and edit your data from your profile.</li>
  <li>Ask for a copy of your data or to delete your account through the <a href="{{ route('home') }}#contact">contact form</a>.</li>
  <li>Turn phone notifications off in your browser settings or by logging out on that device.</li>
</ul>

<h2 id="push">6. Phone notifications</h2>
<p>If you turn notifications on, we keep only your device's notification address. Every message is encrypted before it is sent, so nobody on the way can read it, and notifications stop on the device when you log out.</p>

<h2 id="age">7. Age</h2>
<p>Himma is for people aged {{ $minAge }} or older. Anyone under 18 uses it with a parent's or guardian's consent.</p>

<h2 id="changes">8. Changes and contact</h2>
<p>We may change this policy and will announce important changes in the app. For any question about your data, use the <a href="{{ route('home') }}#contact">contact form</a>.</p>
