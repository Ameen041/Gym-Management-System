<h2 id="account">١. الحساب</h2>
<ul>
  <li>أدخل معلومات صحيحة، واستخدم حساباً واحداً لك وحدك، وحافظ على سرية كلمة المرور. أنت مسؤول عمّا يحدث من حسابك.</li>
</ul>

<h2 id="coaches-role">٢. دور همّة ودور المدرب</h2>
<ul>
  <li>المدربون مستقلون وليسوا موظفين لدى همّة، وكل مدرب مسؤول عن خططه ومتابعته.</li>
  <li>تراجع همّة ملف كل مدرب وشهاداته قبل ظهوره للمتدربين، لكنها لا تضمن نتيجة معيّنة؛ فالنتيجة تعتمد على التزامك وظروفك الصحية.</li>
</ul>

<h2 id="payment">٣. الاشتراك والدفع</h2>
<ul>
  <li>يكون الدفع عبر شام كاش إلى حساب همّة الظاهر في صفحة الدفع فقط، ثم ترفع صورة الإيصال مع رقم العملية.</li>
  <li>يبدأ الاشتراك عندما تؤكد الإدارة وصول المبلغ، ويرسل المدرب خطتك خلال {{ $planDays }} أيام من التأكيد.</li>
  <li>تأخذ همّة عمولة من كل اشتراك، ويرى المدرب صافي أرباحه في لوحته.</li>
  <li><strong>يُمنع الدفع للمدرب مباشرة أو خارج همّة بأي وسيلة.</strong> أي مبلغ يُدفع خارج المنصة لا تضمنه همّة ولا يمكن استرجاعه عن طريقها.</li>
  <li>عند التجديد يبدأ الاشتراك الجديد مباشرة بعد انتهاء الاشتراك الحالي.</li>
</ul>

<h2 id="refunds">٤. الاسترجاع</h2>
<ul>
  <li>إذا لم يرسل المدرب خطتك خلال {{ $planDays }} أيام من تأكيد الدفع، يحق لك استرجاع المبلغ كاملاً أو الانتقال إلى مدرب آخر.</li>
  <li>إذا رُفض الدفع أو ألغيت الاشتراك قبل تأكيده فلا يُخصم منك شيء.</li>
  <li>بعد استلام الخطة لا يُسترجع المبلغ، إلا إذا أخلّ المدرب بالخدمة بشكل واضح (مثل التوقف عن المتابعة). تراجع الإدارة الحالة وتقرّر، وقد يكون الاسترجاع جزئياً بحسب المدة المتبقية.</li>
  <li>يُعاد المبلغ إلى حساب شام كاش الذي دفعت منه. لطلب الاسترجاع استخدم زر «إبلاغ» في المحادثة أو نموذج «تواصل معنا».</li>
</ul>

<h2 id="chat">٥. التواصل داخل همّة</h2>
<ul>
  <li>يتواصل المدرب والمتدرب عبر محادثة همّة فقط، ولا يرى أحدكما رقم هاتف الآخر.</li>
  <li><strong>يُمنع تبادل أرقام الهواتف أو الحسابات أو الروابط أو أسماء الحسابات على التطبيقات الأخرى، أو الاتفاق على الدفع خارج همّة.</strong> لا تُرسَل الرسائل التي تحتوي على ذلك، وتحتفظ بها المنصة.</li>
  <li>المخالفة تؤدي إلى تحذير، وتكرارها قد يؤدي إلى إيقاف الحساب، وإلى إيقاف أرباح المدرب المرتبطة بالمخالفة.</li>
  <li>المحادثة خاصة: لا يقرؤها فريق همّة إلا إذا أبلغ عنها أحد الطرفين أو لحل نزاع.</li>
  <li>تبقى المحادثة مفتوحة طوال الاشتراك و{{ $chatDays }} أيام بعد انتهائه.</li>
  <li>يُمنع الإساءة والتحرش وأي محتوى غير لائق.</li>
</ul>

<h2 id="health">٦. التنبيه الصحي</h2>
<div class="legal-box">
  <ul>
    <li>الخطط والنصائح على همّة إرشادات رياضية وغذائية عامة من مدربك، <strong>وليست تشخيصاً طبياً ولا علاجاً ولا بديلاً عن استشارة الطبيب أو أخصائي التغذية.</strong></li>
    <li>قبل الاشتراك تجيب عن أسئلة صحية. إذا أجبت بـ«نعم» على أي منها، أو كنت تعاني من مرض مزمن، أو كنتِ حاملاً، أو تتناول أدوية، فاستشر طبيبك قبل البدء وأخبر مدربك بما قاله.</li>
    <li><strong>توقّف عن التمرين فوراً واطلب المساعدة الطبية</strong> إذا شعرت بألم في الصدر أو ضيق شديد في التنفس أو دوخة أو إغماء أو ألم غير طبيعي.</li>
    <li>أنت مسؤول عن صحة أجوبتك، وعن إخبار مدربك بأي تغيير في حالتك الصحية.</li>
    <li>الأنظمة الغذائية الخاصة بالأمراض (مثل السكري وأمراض الكلى) تحتاج إشراف طبيب أو أخصائي تغذية.</li>
    <li>لا يصف المدربون على همّة أدوية، ولا يعالجون أمراضاً، ولا يوصون بالمنشطات.</li>
  </ul>
</div>

<h2 id="coaches">٧. شروط خاصة بالمدربين</h2>
<ul>
  <li>تقديم معلومات وشهادات صحيحة، وإرسال الخطة في موعدها، والرد على المتابعات والرسائل.</li>
  <li>مراعاة أجوبة المتدرب الصحية، وإحالته إلى الطبيب عند الحاجة، وعدم تقديم تشخيص طبي أو وصف أدوية أو منشطات.</li>
  <li>عدم طلب أو قبول أي دفع خارج همّة، وعدم مشاركة وسائل تواصل خارجية.</li>
  <li>تصبح أرباح كل اشتراك جاهزة للتحويل بعد إرسال الخطة ومرور فترة الحجز، وتُحوَّل إلى حساب شام كاش الذي أضافه المدرب.</li>
  <li>يحق للإدارة إخفاء ملف المدرب أو إيقاف حسابه عند مخالفة هذه الشروط.</li>
</ul>

<h2 id="content">٨. المحتوى والتقييمات</h2>
<ul>
  <li>يجب أن يكون التقييم صادقاً ويخص تجربتك. تحذف الإدارة التقييمات المسيئة أو المضللة.</li>
  <li>صورك ومتابعاتك خاصة ولا تُنشر.</li>
  <li>محتوى المنصة (التمارين والفيديوهات والتصميم) لهمّة، ولا يُنسخ لأغراض تجارية.</li>
</ul>

<h2 id="ending">٩. إيقاف الحساب وحدود المسؤولية</h2>
<ul>
  <li>يحق لهمّة إيقاف أي حساب يخالف هذه الشروط أو يسيء الاستخدام أو يتحايل على الدفع.</li>
  <li>يمكنك التوقف عن استخدام همّة متى شئت، وحذف حسابك بنفسك من ملفك الشخصي. إذا حذفته أثناء اشتراك فعّال ينتهي الاشتراك دون استرجاع.</li>
  <li>لا تتحمل همّة مسؤولية الإصابات أو الأضرار الناتجة عن عدم الالتزام بالتنبيه الصحي أو إخفاء معلومات صحية، ولا عن أي اتفاق أو دفع خارج المنصة.</li>
  <li>قد تتوقف المنصة مؤقتاً للصيانة أو بسبب انقطاع الإنترنت أو الكهرباء.</li>
  <li>قد نعدّل هذه الشروط، ونعلن عن التعديلات المهمة داخل المنصة، واستمرارك في الاستخدام يعني موافقتك عليها.</li>
