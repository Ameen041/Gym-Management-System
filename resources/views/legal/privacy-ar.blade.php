<p class="legal-lead">نجمع في همّة ما نحتاجه فقط لنقدّم لك الخدمة، ولا نبيع بياناتك لأحد. توضّح هذه الصفحة ما نجمعه، ومن يراه، وكيف تتحكم به.</p>

<h2 id="collect">١. ما الذي نجمعه</h2>
<ul>
  <li><strong>حسابك:</strong> الاسم، البريد الإلكتروني، رقم الهاتف، وكلمة المرور (محفوظة مشفّرة ولا يمكن لأحد قراءتها).</li>
  <li><strong>عند الاشتراك:</strong> العمر، الطول، الوزن، هدفك، أجوبتك الصحية وملاحظاتك، حساسيات الطعام، وصور الجسم إن أضفتها.</li>
  <li><strong>أثناء الاشتراك:</strong> المتابعات الأسبوعية وصورها، رسائل المحادثة، وتقييمك للمدرب.</li>
  <li><strong>الدفع:</strong> صورة إيصال شام كاش ورقم العملية. لا نطلب ولا نحفظ كلمة سر حسابك في شام كاش.</li>
  <li><strong>المدربون:</strong> الملف والشهادات، وحساب شام كاش لتحويل الأرباح.</li>
  <li><strong>تقنياً:</strong> عنوان الشبكة (IP) عند الدخول لحماية الحسابات، وملفات تعريف الارتباط اللازمة لتسجيل الدخول وحفظ اللغة والوضع الليلي. لا نستخدم إعلانات ولا أدوات تتبع.</li>
</ul>

<h2 id="use">٢. لماذا نستخدمها</h2>
<ul>
  <li>ليبني مدربك خطتك ويتابعك بأمان.</li>
  <li>لتأكيد الدفع، وتحويل أرباح المدربين، وحل المشكلات والدعم.</li>
  <li>لحماية المنصة من الاحتيال والدفع خارجها.</li>
  <li>لإرسال الإشعارات داخل همّة وعلى جوالك إذا فعّلتها.</li>
</ul>

<h2 id="who">٣. من يرى بياناتك</h2>
<ul>
  <li><strong>مدربك:</strong> أجوبتك وصورك ومتابعاتك ومحادثتكما. لا يرى رقم هاتفك ولا إيصال الدفع.</li>
  <li><strong>فريق همّة:</strong> لإدارة الاشتراكات والدفع والدعم. لا يقرأ المحادثة إلا إذا أبلغ عنها أحد الطرفين أو لحل نزاع، ويرى الرسائل التي مُنعت لاحتوائها على بيانات تواصل.</li>
  <li><strong>الزوار:</strong> ملف المدرب وصورته وتقييماته عامة. إذا كتبت تقييماً يظهر معه اسمك الأول فقط.</li>
  <li>لا نبيع بياناتك ولا نشاركها مع معلنين، ولا نكشف عنها إلا لجهة رسمية مختصة تطلبها وفق القانون.</li>
</ul>

<h2 id="keep">٤. أين نحفظها وإلى متى</h2>
<ul>
  <li>تُحفظ البيانات على خوادم همّة مع نسخة احتياطية يومية. الصور والإيصالات ليست على رابط عام، ولا تُفتح إلا من حساب من يحق له رؤيتها.</li>
  <li>نحتفظ ببياناتك ما دام حسابك موجوداً. عند حذف الحساب نحذف اسمك وبريدك ورقمك وصورك وأجوبتك الصحية ومتابعاتك ومحادثاتك، ونُبقي سجلات الدفع (المبالغ والتواريخ وأرقام العمليات والإيصالات) دون اسمك لأننا نحتاجها للمحاسبة.</li>
</ul>

<h2 id="rights">٥. حقوقك</h2>
<ul>
  <li>يمكنك رؤية بياناتك وتعديلها من ملفك الشخصي.</li>
  <li>يمكنك حذف حسابك بنفسك من ملفك الشخصي ← «حذف الحساب»، وطلب نسخة من بياناتك عبر نموذج <a href="{{ route('home') }}#contact">«تواصل معنا»</a>.</li>
  <li>يمكنك إيقاف إشعارات الجوال من إعدادات المتصفح أو بتسجيل الخروج من الجهاز.</li>
</ul>

<h2 id="push">٦. إشعارات الجوال</h2>
<p>إذا فعّلت الإشعارات نحفظ عنوان الإشعار الخاص بجهازك فقط. تُشفَّر كل رسالة قبل إرسالها فلا يقرؤها أحد في الطريق، وتتوقف الإشعارات على الجهاز عند تسجيل الخروج.</p>

